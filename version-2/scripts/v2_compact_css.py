"""Generate src/v2/compact.css: every phone rule (@media (max-width: 860px)) from src/app/globals.css and
src/v2/v2.css, repeated under `html.compact`, the class Variant 2 sets on portrait screens that are wider
than a phone (tablets, narrow windows) so they get the phone layout too. Re-run after editing phone rules:

    python3 scripts/v2_compact_css.py
"""
import re

SOURCES = ["src/app/globals.css", "src/v2/v2.css"]
OUT = "src/v2/compact.css"
MQ = re.compile(r"@media\s*\(max-width:\s*860px\)\s*\{")


def blocks(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    for m in MQ.finditer(css):
        i, depth = m.end(), 1
        j = i
        while depth and j < len(css):
            depth += {"{": 1, "}": -1}.get(css[j], 0)
            j += 1
        yield css[i : j - 1]


def prefix(sel):
    sel = sel.strip()
    if sel.startswith(":root") or sel.startswith("html"):
        return "html.compact" + re.sub(r"^(:root|html)", "", sel)
    return "html.compact " + sel


out = ["/* generated by scripts/v2_compact_css.py from the phone rules: do not edit by hand */"]
for src in SOURCES:
    for blk in blocks(open(src).read()):
        for r in re.finditer(r"([^{}]+)\{([^{}]*)\}", blk):
            sels = ", ".join(prefix(s) for s in r.group(1).split(","))
            body = "\n".join("  " + l.strip() for l in r.group(2).strip().split(";") if l.strip())
            out.append(f"{sels} {{\n{body.replace(chr(10), ';' + chr(10))};\n}}")
open(OUT, "w").write("\n".join(out) + "\n")
print(OUT, len(out) - 1, "rules")
